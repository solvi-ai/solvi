"""A law set as plain code: `Law.to_code`, `LawSet.to_module`, and the differential check `check_compiled` that runs the
compiled module against the law set's own predictions on every buffer row (see the package docstring)."""
from __future__ import annotations

import ast as _ast
import types
from dataclasses import dataclass, field
from typing import Any

_NO_MODULE_IMPORTS = "# generated by solvi.experimental.laws; it imports nothing from solvi"


def _literal(x, what: str) -> str:
    """The source of `x` if it reads back as itself (a literal), else ValueError naming `what`."""
    src = repr(x)
    try:
        ok = _ast.literal_eval(src) == x
    except (ValueError, SyntaxError, TypeError, MemoryError, RecursionError):
        ok = False
    if not ok:
        raise ValueError(f"{what} {src[:60]} is not a literal (repr does not read back as itself): it cannot be "
                         f"compiled")
    return src


def _fn_name(law) -> str:
    return "law_" + "".join(ch if ch.isalnum() else "_" for ch in str(law.id).removeprefix("law-"))


def missing_code(grammar, condition) -> list[str]:
    """The atoms of `condition` that carry no code."""
    return [x for x in condition if grammar.by_name[x].code is None]


def law_to_code(law, grammar, name: str | None = None) -> str:
    """The source of `def <name>(s, a)`: (True, effect) where the law applies to action `a` in state `s`, else
    (False, None). ValueError: an atom without code (named), an action or effect that is not a literal."""
    miss = missing_code(grammar, law.condition)
    if miss:
        raise ValueError(f"{law.id}: atoms without code {miss} (give Atom(..., code=...) to compile them)")
    name = name or _fn_name(law)
    act = _literal(law.action, f"{law.id}: the action")
    eff = _literal(law.effect, f"{law.id}: the effect")
    test = " and ".join([f"a == {act}"] + [f"bool({grammar.by_name[x].code})" for x in law.condition])
    text = law.text().replace("\n", " ")
    return (f"def {name}(s, a):\n"
            f"    # {text}\n"
            f"    if {test}:\n"
            f"        return True, {eff}\n"
            f"    return False, None\n")


def lawset_to_module(lawset) -> str:
    """One module for the active laws: the atoms' defs (each once), one function per law, LAWS in dispatch order
    (most specific first, ties by the set's `ties` — the law set's own order), applied(s, a) → the law id or None,
    predict(s, a, base=None, apply=None) → the first applying law's effect (through `apply` if given), else
    base(s, a), else None. ValueError naming every atom without code."""
    miss = sorted({x for law in lawset.laws for x in missing_code(lawset.grammar, law.condition)})
    if miss:
        raise ValueError(f"atoms without code {miss}: give Atom(..., code=...) to compile them")
    defs: list[str] = []
    for law in lawset.laws:
        for x in law.condition:
            for d in lawset.grammar.by_name[x].defs:
                if d not in defs:
                    defs.append(d)
    fns = [law_to_code(law, lawset.grammar) for law in lawset.laws]
    table = ", ".join(f"({law.id!r}, {_fn_name(law)})" for law in lawset.laws)
    parts = [f'"""A compiled law set: {len(lawset.laws)} laws, most specific first, the base predictor as the '
             f'fallback."""', _NO_MODULE_IMPORTS, *[d.rstrip("\n") for d in defs], *[f.rstrip("\n") for f in fns],
             f"LAWS = ({table}{',' if len(lawset.laws) == 1 else ''})",
             _DISPATCH]
    return "\n\n\n".join(parts) + "\n"


_DISPATCH = '''def applied(s, a):
    """The id of the first law that applies to action `a` in state `s`, or None."""
    for lid, fn in LAWS:
        if fn(s, a)[0]:
            return lid
    return None


def predict(s, a, base=None, apply=None):
    """The first applying law's effect (apply(effect, s) if given), else base(s, a) if given, else None."""
    for _, fn in LAWS:
        hit, effect = fn(s, a)
        if hit:
            return apply(effect, s) if apply is not None else effect
    return base(s, a) if base is not None else None'''


def load_module(source: str, name: str = "compiled_laws") -> types.ModuleType:
    """Execute generated source as a fresh module (not registered in sys.modules)."""
    mod = types.ModuleType(name)
    exec(compile(source, f"<{name}>", "exec"), mod.__dict__)   # noqa: S102 — code generated by to_module
    return mod


@dataclass
class CompiledCheck:
    """The differential check: rows compared, how many differed (the bar is 0), and up to 20 differing rows as
    {"id", "action", "compiled", "interpreted"} (each side: (law id, prediction))."""
    rows: int
    differences: int
    examples: list = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.differences == 0


def check_compiled(module: Any, buffer, lawset, *, limit: int = 20) -> CompiledCheck:
    """Run the compiled module (source or module) against `lawset` on every row of `buffer`: the applied law's id and
    the prediction must agree on each row."""
    mod = load_module(module) if isinstance(module, str) else module
    apply = lawset.apply                                     # the default apply returns the effect itself
    rows = buffer.rows()
    diffs, examples = 0, []
    for t in rows:
        law = lawset.applied(t.state, t.action)
        want = (law.id if law is not None else None, lawset.predict(t.state, t.action, disagree="first"))
        got = (mod.applied(t.state, t.action), mod.predict(t.state, t.action, base=lawset.base, apply=apply))
        if got != want:
            diffs += 1
            if len(examples) < limit:
                examples.append({"id": t.id, "action": t.action, "compiled": got, "interpreted": want})
    return CompiledCheck(len(rows), diffs, examples)


__all__ = ["CompiledCheck", "check_compiled", "law_to_code", "lawset_to_module", "load_module"]
